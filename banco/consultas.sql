-- 1. Situação de cada estação
SELECT l.NUMERO AS LINHA,
       e.NOME   AS ESTACAO,
       COUNT(q.ID_EQUIPAMENTO) AS EQUIPAMENTOS,
       SUM(CASE WHEN q.STATUS <> 'OPERANDO' THEN 1 ELSE 0 END) AS FORA_DE_SERVICO
  FROM TB_ESTACAO e
  JOIN TB_LINHA l ON l.ID_LINHA = e.ID_LINHA
  LEFT JOIN TB_EQUIPAMENTO q ON q.ID_ESTACAO = e.ID_ESTACAO
 GROUP BY l.NUMERO, e.NOME, e.ORDEM
 ORDER BY l.NUMERO, e.ORDEM;

-- 2. Estações totalmente acessíveis por linha
SELECT l.NUMERO AS LINHA, l.NOME AS NOME_LINHA, e.NOME AS ESTACAO, e.ORDEM
  FROM TB_ESTACAO e
  JOIN TB_LINHA l ON l.ID_LINHA = e.ID_LINHA
  JOIN TB_EQUIPAMENTO q ON q.ID_ESTACAO = e.ID_ESTACAO
 WHERE q.TIPO IN ('ELEVADOR', 'PLATAFORMA')
 GROUP BY l.NUMERO, l.NOME, e.NOME, e.ORDEM
HAVING SUM(CASE WHEN q.STATUS <> 'OPERANDO' THEN 1 ELSE 0 END) = 0
 ORDER BY l.NUMERO, e.ORDEM;

-- 3. Equipamentos com mais tempo parado em 30 dias
SELECT l.NUMERO AS LINHA,
       e.NOME   AS ESTACAO,
       q.TIPO,
       q.LOCALIZACAO,
       COUNT(a.ID_ALERTA) AS PARADAS,
       ROUND(SUM(
         EXTRACT(DAY    FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM)) * 1440 +
         EXTRACT(HOUR   FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM)) * 60 +
         EXTRACT(MINUTE FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM))
       )) AS MINUTOS_PARADO
  FROM TB_ALERTA a
  JOIN TB_EQUIPAMENTO q ON q.ID_EQUIPAMENTO = a.ID_EQUIPAMENTO
  JOIN TB_ESTACAO e ON e.ID_ESTACAO = q.ID_ESTACAO
  JOIN TB_LINHA l ON l.ID_LINHA = e.ID_LINHA
 WHERE a.ABERTO_EM >= SYS_EXTRACT_UTC(SYSTIMESTAMP) - INTERVAL '30' DAY
 GROUP BY l.NUMERO, e.NOME, q.TIPO, q.LOCALIZACAO
 ORDER BY MINUTOS_PARADO DESC;

-- 4. Alertas abertos nas estações favoritas de um usuário
SELECT l.NUMERO AS LINHA, e.NOME AS ESTACAO, q.TIPO, q.LOCALIZACAO, a.MOTIVO, a.ABERTO_EM
  FROM TB_FAVORITO f
  JOIN TB_ESTACAO e ON e.ID_ESTACAO = f.ID_ESTACAO
  JOIN TB_LINHA l ON l.ID_LINHA = e.ID_LINHA
  JOIN TB_EQUIPAMENTO q ON q.ID_ESTACAO = e.ID_ESTACAO
  JOIN TB_ALERTA a ON a.ID_EQUIPAMENTO = q.ID_EQUIPAMENTO
 WHERE f.ID_USUARIO = 2
   AND a.ENCERRADO_EM IS NULL
 ORDER BY a.ABERTO_EM DESC;

-- 5. Leituras de cada sensor nas últimas 24 horas
SELECT s.CODIGO,
       s.TIPO,
       s.LIMITE,
       COUNT(r.ID_LEITURA)                  AS LEITURAS,
       ROUND(AVG(r.VALOR), 1)               AS MEDIA,
       MAX(r.VALOR)                         AS MAXIMO,
       ROUND(MAX(r.VALOR) / s.LIMITE * 100) AS PCT_DO_LIMITE
  FROM TB_SENSOR s
  JOIN TB_LEITURA r ON r.ID_SENSOR = s.ID_SENSOR
 WHERE r.REGISTRADA_EM >= SYS_EXTRACT_UTC(SYSTIMESTAMP) - INTERVAL '1' DAY
 GROUP BY s.CODIGO, s.TIPO, s.LIMITE
 ORDER BY PCT_DO_LIMITE DESC, s.CODIGO;

-- 6. Relatos por estação e situação
SELECT l.NUMERO AS LINHA,
       e.NOME   AS ESTACAO,
       r.STATUS,
       COUNT(*) AS RELATOS,
       COUNT(DISTINCT r.ID_USUARIO) AS CIDADAOS,
       MAX(r.CRIADO_EM) AS MAIS_RECENTE
  FROM TB_RELATO r
  JOIN TB_EQUIPAMENTO q ON q.ID_EQUIPAMENTO = r.ID_EQUIPAMENTO
  JOIN TB_ESTACAO e ON e.ID_ESTACAO = q.ID_ESTACAO
  JOIN TB_LINHA l ON l.ID_LINHA = e.ID_LINHA
 GROUP BY l.NUMERO, e.NOME, r.STATUS
 ORDER BY RELATOS DESC, l.NUMERO, e.NOME;

-- 7. Disponibilidade por linha em 30 dias
SELECT l.NUMERO AS LINHA,
       l.NOME   AS NOME_LINHA,
       COUNT(DISTINCT q.ID_EQUIPAMENTO) AS EQUIPAMENTOS,
       ROUND(100 - NVL(SUM(
         EXTRACT(DAY    FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM)) * 1440 +
         EXTRACT(HOUR   FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM)) * 60 +
         EXTRACT(MINUTE FROM (NVL(a.ENCERRADO_EM, SYS_EXTRACT_UTC(SYSTIMESTAMP)) - a.ABERTO_EM))
       ), 0) / (COUNT(DISTINCT q.ID_EQUIPAMENTO) * 30 * 1440) * 100, 2) AS DISPONIBILIDADE_PCT
  FROM TB_LINHA l
  JOIN TB_ESTACAO e ON e.ID_LINHA = l.ID_LINHA
  JOIN TB_EQUIPAMENTO q ON q.ID_ESTACAO = e.ID_ESTACAO AND q.TIPO IN ('ELEVADOR', 'PLATAFORMA')
  LEFT JOIN TB_ALERTA a ON a.ID_EQUIPAMENTO = q.ID_EQUIPAMENTO
                       AND a.ABERTO_EM >= SYS_EXTRACT_UTC(SYSTIMESTAMP) - INTERVAL '30' DAY
 GROUP BY l.NUMERO, l.NOME
 ORDER BY l.NUMERO;
