BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('TB_RELATO', 'TB_FAVORITO', 'TB_ALERTA', 'TB_LEITURA', 'TB_SENSOR',
                                  'TB_EQUIPAMENTO', 'TB_ESTACAO', 'TB_LINHA', 'TB_USUARIO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE TB_USUARIO (
  ID_USUARIO  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME        VARCHAR2(120) NOT NULL,
  EMAIL       VARCHAR2(160) NOT NULL,
  SENHA_HASH  VARCHAR2(200) NOT NULL,
  PERFIL      VARCHAR2(10)  DEFAULT 'CIDADAO' NOT NULL,
  CRIADO_EM   TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('ADMIN', 'CIDADAO')),
  CONSTRAINT CK_USUARIO_EMAIL CHECK (EMAIL = LOWER(EMAIL) AND EMAIL LIKE '_%@_%')
);

CREATE TABLE TB_LINHA (
  ID_LINHA   NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NUMERO     NUMBER(3)    NOT NULL,
  NOME       VARCHAR2(40) NOT NULL,
  COR        CHAR(7)      NOT NULL,
  OPERADORA  VARCHAR2(60) NOT NULL,
  CONSTRAINT PK_LINHA PRIMARY KEY (ID_LINHA),
  CONSTRAINT UK_LINHA_NUMERO UNIQUE (NUMERO),
  CONSTRAINT CK_LINHA_COR CHECK (REGEXP_LIKE(COR, '^#[0-9A-F]{6}$'))
);

CREATE TABLE TB_ESTACAO (
  ID_ESTACAO  NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_LINHA    NUMBER(10)   NOT NULL,
  NOME        VARCHAR2(80) NOT NULL,
  ORDEM       NUMBER(3)    NOT NULL,
  CONSTRAINT PK_ESTACAO PRIMARY KEY (ID_ESTACAO),
  CONSTRAINT FK_ESTACAO_LINHA FOREIGN KEY (ID_LINHA) REFERENCES TB_LINHA (ID_LINHA),
  CONSTRAINT UK_ESTACAO_NOME UNIQUE (ID_LINHA, NOME),
  CONSTRAINT UK_ESTACAO_ORDEM UNIQUE (ID_LINHA, ORDEM),
  CONSTRAINT CK_ESTACAO_ORDEM CHECK (ORDEM > 0)
);

CREATE TABLE TB_EQUIPAMENTO (
  ID_EQUIPAMENTO  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_ESTACAO      NUMBER(10)    NOT NULL,
  TIPO            VARCHAR2(20)  NOT NULL,
  LOCALIZACAO     VARCHAR2(120) NOT NULL,
  STATUS          VARCHAR2(12)  DEFAULT 'OPERANDO' NOT NULL,
  STATUS_DESDE    TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT PK_EQUIPAMENTO PRIMARY KEY (ID_EQUIPAMENTO),
  CONSTRAINT FK_EQUIPAMENTO_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES TB_ESTACAO (ID_ESTACAO) ON DELETE CASCADE,
  CONSTRAINT CK_EQUIPAMENTO_TIPO CHECK (TIPO IN ('ELEVADOR', 'ESCADA_ROLANTE', 'PLATAFORMA')),
  CONSTRAINT CK_EQUIPAMENTO_STATUS CHECK (STATUS IN ('OPERANDO', 'PARADO', 'MANUTENCAO'))
);

CREATE TABLE TB_SENSOR (
  ID_SENSOR       NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_EQUIPAMENTO  NUMBER(10)   NOT NULL,
  TIPO            VARCHAR2(12) NOT NULL,
  CODIGO          VARCHAR2(40) NOT NULL,
  LIMITE          NUMBER(8,2)  NOT NULL,
  UNIDADE         VARCHAR2(10) NOT NULL,
  ATIVO           NUMBER(1)    DEFAULT 1 NOT NULL,
  CONSTRAINT PK_SENSOR PRIMARY KEY (ID_SENSOR),
  CONSTRAINT FK_SENSOR_EQUIPAMENTO FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES TB_EQUIPAMENTO (ID_EQUIPAMENTO) ON DELETE CASCADE,
  CONSTRAINT UK_SENSOR_CODIGO UNIQUE (CODIGO),
  CONSTRAINT UK_SENSOR_TIPO UNIQUE (ID_EQUIPAMENTO, TIPO),
  CONSTRAINT CK_SENSOR_TIPO CHECK (TIPO IN ('MOVIMENTO', 'PORTA')),
  CONSTRAINT CK_SENSOR_LIMITE CHECK (LIMITE > 0),
  CONSTRAINT CK_SENSOR_ATIVO CHECK (ATIVO IN (0, 1))
);

CREATE TABLE TB_LEITURA (
  ID_LEITURA     NUMBER(12)  GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_SENSOR      NUMBER(10)  NOT NULL,
  VALOR          NUMBER(8,2) NOT NULL,
  REGISTRADA_EM  TIMESTAMP   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT PK_LEITURA PRIMARY KEY (ID_LEITURA),
  CONSTRAINT FK_LEITURA_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES TB_SENSOR (ID_SENSOR) ON DELETE CASCADE,
  CONSTRAINT CK_LEITURA_VALOR CHECK (VALOR >= 0)
);

CREATE INDEX IX_LEITURA_SENSOR ON TB_LEITURA (ID_SENSOR, REGISTRADA_EM);

CREATE TABLE TB_ALERTA (
  ID_ALERTA       NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_EQUIPAMENTO  NUMBER(10)    NOT NULL,
  ID_SENSOR       NUMBER(10),
  MOTIVO          VARCHAR2(200) NOT NULL,
  ABERTO_EM       TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  ENCERRADO_EM    TIMESTAMP,
  CONSTRAINT PK_ALERTA PRIMARY KEY (ID_ALERTA),
  CONSTRAINT FK_ALERTA_EQUIPAMENTO FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES TB_EQUIPAMENTO (ID_EQUIPAMENTO) ON DELETE CASCADE,
  CONSTRAINT FK_ALERTA_SENSOR FOREIGN KEY (ID_SENSOR) REFERENCES TB_SENSOR (ID_SENSOR) ON DELETE SET NULL,
  CONSTRAINT CK_ALERTA_PERIODO CHECK (ENCERRADO_EM IS NULL OR ENCERRADO_EM >= ABERTO_EM)
);

CREATE INDEX IX_ALERTA_EQUIPAMENTO ON TB_ALERTA (ID_EQUIPAMENTO, ABERTO_EM);

CREATE TABLE TB_FAVORITO (
  ID_USUARIO  NUMBER(10) NOT NULL,
  ID_ESTACAO  NUMBER(10) NOT NULL,
  CRIADO_EM   TIMESTAMP  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT PK_FAVORITO PRIMARY KEY (ID_USUARIO, ID_ESTACAO),
  CONSTRAINT FK_FAVORITO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO) ON DELETE CASCADE,
  CONSTRAINT FK_FAVORITO_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES TB_ESTACAO (ID_ESTACAO) ON DELETE CASCADE
);

CREATE TABLE TB_RELATO (
  ID_RELATO       NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_USUARIO      NUMBER(10)    NOT NULL,
  ID_EQUIPAMENTO  NUMBER(10)    NOT NULL,
  DESCRICAO       VARCHAR2(500) NOT NULL,
  STATUS          VARCHAR2(12)  DEFAULT 'ABERTO' NOT NULL,
  CRIADO_EM       TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  ATUALIZADO_EM   TIMESTAMP     DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
  CONSTRAINT PK_RELATO PRIMARY KEY (ID_RELATO),
  CONSTRAINT FK_RELATO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO) ON DELETE CASCADE,
  CONSTRAINT FK_RELATO_EQUIPAMENTO FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES TB_EQUIPAMENTO (ID_EQUIPAMENTO) ON DELETE CASCADE,
  CONSTRAINT CK_RELATO_STATUS CHECK (STATUS IN ('ABERTO', 'CONFIRMADO', 'RESOLVIDO', 'DESCARTADO')),
  CONSTRAINT CK_RELATO_DESCRICAO CHECK (LENGTH(TRIM(DESCRICAO)) >= 5)
);

